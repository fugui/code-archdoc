func TestNormalizeSubdir(t *testing.T) {
	valid := []struct {
		in   string
		want string
	}{
		{"", ""},
		{"   ", ""},
		{".", ""},
		{"./", ""},
		{"svc/order", "svc/order"},
		{"svc/order/", "svc/order"},
		{"  svc//order///  ", "svc/order"},
		{"./svc/order", "svc/order"},
	}
	for _, tc := range valid {
		got, err := NormalizeSubdir(tc.in)
		if err != nil {
			t.Errorf("NormalizeSubdir(%q) 意外失败: %v", tc.in, err)
			continue
		}
		if got != tc.want {
			t.Errorf("NormalizeSubdir(%q) = %q, want %q", tc.in, got, tc.want)
		}
	}

	invalid := []string{
		"..",
		"../../etc",
		"svc/../../etc",
		"/etc/passwd",
		"a\x00b",
		`a\b`,
		`svc\order`,
	}
	for _, raw := range invalid {
		got, err := NormalizeSubdir(raw)
		if !errors.Is(err, ErrInvalidSubdir) {
			t.Errorf("NormalizeSubdir(%q) 期望返回 ErrInvalidSubdir，实际 got=%q err=%v", raw, got, err)
		}
	}
}

func TestSafeJoinBlocksTraversalAndSymlinkEscape(t *testing.T) {
	base := t.TempDir()
	sandboxRoot := filepath.Join(base, "sandbox")
	siblingDir := filepath.Join(base, "sandbox-malicious")
	outsideFile := filepath.Join(siblingDir, "secret.txt")

	if err := os.MkdirAll(filepath.Join(sandboxRoot, "src"), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(siblingDir, 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(sandboxRoot, "src", "main.cpp"), []byte("int main(){}\n"), 0644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(outsideFile, []byte("outside secret\n"), 0644); err != nil {
		t.Fatal(err)
	}

	// 创建指向沙箱外文件的恶意符号链接
	evilLink := filepath.Join(sandboxRoot, "src", "escape_link.txt")
	if err := os.Symlink(outsideFile, evilLink); err != nil {
		t.Fatal(err)
	}
	// 创建指向沙箱外目录的符号链接
	evilDirLink := filepath.Join(sandboxRoot, "evil_dir")
	if err := os.Symlink(siblingDir, evilDirLink); err != nil {
		t.Fatal(err)
	}
	// 创建指向沙箱内部的合法符号链接
	goodLink := filepath.Join(sandboxRoot, "src", "good_link.cpp")
	if err := os.Symlink(filepath.Join(sandboxRoot, "src", "main.cpp"), goodLink); err != nil {
		t.Fatal(err)
	}

	// 1. 合法路径与沙箱内部符号链接应放行
	if resolved, err := SafeJoin(sandboxRoot, "src/main.cpp"); err != nil {
		t.Fatalf("合法路径 SafeJoin 失败: %v", err)
	} else if !filepath.IsAbs(resolved) {
		t.Fatalf("期望返回绝对路径，实际为 %q", resolved)
	}
	if _, err := SafeJoin(sandboxRoot, "src/good_link.cpp"); err != nil {
		t.Fatalf("沙箱内部合法符号链接应放行，实际失败: %v", err)
	}
	// 不存在但位于沙箱内的路径也应放行（如准备创建的文件）
	if _, err := SafeJoin(sandboxRoot, "src/new_file.cpp"); err != nil {
		t.Fatalf("沙箱内待新建文件路径应放行，实际失败: %v", err)
	}

	// 2. 目录穿越、兄弟前缀绕过、外部符号链接均必须返回 ErrPathEscape
	escapeCases := []string{
		"../outside.txt",
		"../sandbox-malicious/secret.txt",
		"src/../../etc/passwd",
		"/etc/passwd",
		"src/escape_link.txt",
		"evil_dir/secret.txt",
		"evil_dir/nonexistent.txt",
		"src/bad\x00name.cpp",
	}
	for _, rel := range escapeCases {
		got, err := SafeJoin(sandboxRoot, rel)
		if !errors.Is(err, ErrPathEscape) {
			t.Errorf("SafeJoin(%q) 期望返回 ErrPathEscape，实际 got=%q err=%v", rel, got, err)
		}
	}
}

func TestFileWalkerThreeLayerNoiseFilter(t *testing.T) {
	base := t.TempDir()
	repoRoot := filepath.Join(base, "repo")
	outsideFile := filepath.Join(base, "outside.cpp")
	if err := os.WriteFile(outsideFile, []byte("// outside\n"), 0644); err != nil {
		t.Fatal(err)
	}

	writeFixture := func(rel string, data []byte) {
		full := filepath.Join(repoRoot, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(full), 0755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, data, 0644); err != nil {
			t.Fatal(err)
		}
	}

	// 常规有效源码
	writeFixture("src/order.cpp", []byte("int pay() { return 0; }\n"))
	writeFixture("src/order_test.cpp", []byte("void test_pay() {}\n"))
	// Layer 1: 第三方依赖与自动生成代码
	writeFixture("third_party/zlib/z.c", []byte("int z() { return 1; }\n"))
	writeFixture("third_party/allowed/keep.h", []byte("#pragma once\n"))
	writeFixture("proto/order.pb.cc", []byte("// generated by protoc\n"))
	writeFixture("proto/order.proto", []byte("syntax = \"proto3\";\n"))
	// Layer 1: 二进制文件（前 512 字节含 \x00）与超大文件
	writeFixture("assets/bin.dat", []byte{'E', 'L', 'F', 0x00, 0x01, 0x02})
	writeFixture("data/oversize.txt", bytes.Repeat([]byte("a"), 2048))
	// Layer 1 硬保护: .git/
	writeFixture(".git/config", []byte("[core]\n"))
	// Layer 2: .archdocignore 排除 fixtures/ 并放行 third_party/allowed/keep.h，同时尝试放行 .git/config（应被硬保护忽略）
	writeFixture("fixtures/noisy.cpp", []byte("// fixture\n"))
	writeFixture(".archdocignore", []byte("# custom rules\nfixtures/\n!third_party/allowed/keep.h\n!.git/config\n"))

	// 外部符号链接（应跳过并计数，绝不读取）
	if err := os.Symlink(outsideFile, filepath.Join(repoRoot, "src", "evil_symlink.cpp")); err != nil {
		t.Fatal(err)
	}

	walker := NewFileWalker()
	res, err := walker.Walk(context.Background(), repoRoot, "", WalkOptions{
		MaxFileBytes: 1024, // 1KB 上限以触发 data/oversize.txt 过滤
	})
	if err != nil {
		t.Fatalf("Walk 失败: %v", err)
	}

	gotPaths := make(map[string]bool, len(res.Files))
	for _, f := range res.Files {
		gotPaths[f.RelPath] = true
	}

	// 必须保留的文件
	for _, mustKeep := range []string{"src/order.cpp", "src/order_test.cpp", "proto/order.proto", "third_party/allowed/keep.h"} {
		if !gotPaths[mustKeep] {
			t.Errorf("期望保留文件 %q，但未出现在结果中: %+v", mustKeep, gotPaths)
		}
	}
	// 必须排除的文件
	for _, mustDrop := range []string{
		"third_party/zlib/z.c",
		"proto/order.pb.cc",
		"assets/bin.dat",
		"data/oversize.txt",
		"fixtures/noisy.cpp",
		".git/config",
		"src/evil_symlink.cpp",
	} {
		if gotPaths[mustDrop] {
			t.Errorf("期望排除文件 %q，但它出现在结果中", mustDrop)
		}
	}

	// 校验按规则分类的跳过统计
	if res.Stats.SkippedByRule[RuleThirdParty] < 1 {
		t.Errorf("期望 third_party 跳过计数 >= 1，实际为 %d", res.Stats.SkippedByRule[RuleThirdParty])
	}
	if res.Stats.SkippedByRule[RuleGenerated] < 1 {
		t.Errorf("期望 generated 跳过计数 >= 1，实际为 %d", res.Stats.SkippedByRule[RuleGenerated])
	}
	if res.Stats.SkippedByRule[RuleBinary] < 1 {
		t.Errorf("期望 binary 跳过计数 >= 1，实际为 %d", res.Stats.SkippedByRule[RuleBinary])
	}
	if res.Stats.SkippedByRule[RuleOversize] < 1 {
		t.Errorf("期望 oversize 跳过计数 >= 1，实际为 %d", res.Stats.SkippedByRule[RuleOversize])
	}
	if res.Stats.SkippedByRule[RuleArchdocIgnore] < 1 {
		t.Errorf("期望 archdocignore 跳过计数 >= 1，实际为 %d", res.Stats.SkippedByRule[RuleArchdocIgnore])
	}
	if res.Stats.SkippedByRule[RuleExternalSymlink] < 1 {
		t.Errorf("期望 external_symlink 跳过计数 >= 1，实际为 %d", res.Stats.SkippedByRule[RuleExternalSymlink])
	}

	// 验证 Layer 3 ScopeProfile 过滤接口（仅保留 *.proto 且排除测试文件）
	filtered := FilterByScopeProfile(res.Files, &ScopeProfile{
		IncludeGlobs: []string{"**/*.proto", "src/*.cpp"},
		IncludeTests: false,
	})
	filteredMap := make(map[string]bool, len(filtered))
	for _, f := range filtered {
		filteredMap[f.RelPath] = true
	}
	if !filteredMap["proto/order.proto"] || !filteredMap["src/order.cpp"] || filteredMap["src/order_test.cpp"] || filteredMap["third_party/allowed/keep.h"] {
		t.Fatalf("Layer 3 ScopeProfile 过滤结果不符: %+v", filteredMap)
	}
}
